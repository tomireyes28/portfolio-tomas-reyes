import { createRequire } from 'node:module';
import { mkdir, stat, writeFile } from 'node:fs/promises';

// Reuse the Sharp dependency installed by Next's image optimizer.
const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve('next/package.json'))('sharp');
const assets = [
  ['plastic-who', 'plastic-who.png'], ['mn-agency', 'mn-agency.png'],
  ['therapio', 'psychomanager.png'], ['lumi', 'lumi.png'],
  ['mn-igx-sync', 'ig-x-sync.jpg'], ['cinema-agenda', 'cinemaapp.png'],
  ['aberturas-nyl', 'aberturas-nyl.png'], ['dea-simulator', 'dea-simulador.png'],
];
await mkdir('public/projects/optimized', { recursive: true });
const images = {};
let before = 0, after = 0;
for (const [id, source] of assets) {
  const input = `public/projects/${source}`;
  const image = `/projects/optimized/${id}.webp`;
  const info = await sharp(input).resize({ width: 1600, withoutEnlargement: true }).webp({ quality: 85, effort: 6 }).toFile(`public${image}`);
  images[id] = { image, imageWidth: info.width, imageHeight: info.height };
  before += (await stat(input)).size;
  after += info.size;
}
await writeFile('src/projectImages.ts', `// Generated by npm run images:optimize. Originals remain in public/projects.\nexport const projectImages = ${JSON.stringify(images, null, 2)} as const;\n`);
console.log(JSON.stringify({ originalBytes: before, optimizedBytes: after, savedPercent: Math.round((1 - after / before) * 100) }));
